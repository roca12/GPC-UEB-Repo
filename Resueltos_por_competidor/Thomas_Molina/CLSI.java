public class CLSI
{
	public static void main (String[] args)
	{
		Scanner sc = new Scanner(System.in);
		
		int n = sc.nextInt();
		
		int B = sc.nextInt();
		
		if(B * 10 <= n){
		    System.out.println("YES");
		}
		else{
		    System.out.println("NO");
		}
		

	}
}
