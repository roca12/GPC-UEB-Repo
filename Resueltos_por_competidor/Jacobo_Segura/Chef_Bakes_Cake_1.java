import java.util.*;
import java.lang.*;
import java.io.*;

class Codechef
{
	public static void main (String[] args) throws java.lang.Exception
	{
	    Scanner sc = new Scanner(System.in);
	    int np, nm, g;
	    int n = sc.nextInt();
	    int m = sc.nextInt();
	    np = n*30;
	    nm = m*50;
	    
	    g = nm-np;
	    System.out.println(g);
	}
}
